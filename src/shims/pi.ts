// steer's pi extension. pi loads extensions into its own process rather than
// spawning anything, so this file runs the steer binary and turns its answer
// into a block or an edited command.
//
// Nothing is imported on purpose: no package has to resolve for the file to
// work. pi's own objects therefore have no types to name, and the parameters
// below say `any` so the file is clean under the `strict` tsconfig of whatever
// project `steer init` writes it into.
//
// pi only loads a project's extensions once the project is trusted, and answers
// no trust prompt in `-p` and the other non-interactive modes. An extension
// that appears to do nothing there is usually that.
//
// Generated by `steer init --agent pi`, which refuses to overwrite an existing
// file. An edit here survives, and stops matching the binary it talks to: after
// upgrading steer, run that command again with `--force`.

const TIMEOUT_MS = 5000;

// pi's subprocess API hands the child no stdin at all, so the payload rides in
// argv and a shell pipes it back to where steer reads it. As `$1` rather than
// inside the script, which leaves nothing to quote.
const PIPE = 'printf \'%s\' "$1" | steer hook --event PreToolUse --agent pi';

// The one place steer's fail-open guarantee leaves Rust: every failure returns
// null, and null lets the tool call through untouched.
//
// `pi.exec` resolves rather than rejecting when the binary is missing, and
// reports it as an exit of 1 — indistinguishable from steer failing.
async function ask(pi: any, ctx: any, payload: any) {
  try {
    const result = await pi.exec("sh", ["-c", PIPE, "steer", JSON.stringify(payload)], {
      cwd: ctx.cwd,
      signal: ctx.signal,
      timeout: TIMEOUT_MS,
    });
    if (result.code !== 0) {
      return null;
    }
    const answer = JSON.parse(result.stdout);
    return typeof answer.outcome === "string" ? answer : null;
  } catch {
    return null;
  }
}

export default function (pi: any) {
  pi.on("tool_call", async (event: any, ctx: any) => {
    // The fields that carry file text, dropped so the payload stays well
    // inside the argument-length limit — `oldText` and `newText` are `edit`'s
    // older flat form. No rule reads any of them: a rule about a file gates on
    // `path`, which survives.
    const { content, edits, oldText, newText, ...input } = event.input ?? {};
    const answer = await ask(pi, ctx, {
      toolName: event.toolName,
      input,
      cwd: ctx.cwd,
    });
    if (!answer) {
      return undefined;
    }
    if (answer.outcome === "deny") {
      return { block: true, reason: answer.message };
    }
    if (answer.outcome === "rewrite") {
      // pi hands this same object to the tool; reassigning `event.input` would
      // drop the edit.
      event.input.command = answer.updated_command;
    } else if (answer.message) {
      // A message on an allowed call is steer reporting a broken config.
      console.error(answer.message);
    }
    return undefined;
  });
}
